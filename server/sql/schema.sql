-- ------------------------------------------------------------
-- Grupos de amigos (P1)
-- ------------------------------------------------------------
CREATE TABLE grupo (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome        VARCHAR2(120) NOT NULL,
  criador_id  NUMBER NOT NULL,
  membros_podem_adicionar CHAR(1) DEFAULT 'N' NOT NULL,
  criado_em   TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT fk_grupo_criador FOREIGN KEY (criador_id)
    REFERENCES usuario (id),
  CONSTRAINT ck_grupo_adicionar CHECK (membros_podem_adicionar IN ('S', 'N'))
);

CREATE TABLE grupo_membro (
  grupo_id   NUMBER NOT NULL,
  usuario_id NUMBER NOT NULL,
  papel      VARCHAR2(10) DEFAULT 'MEMBRO' NOT NULL,
  criado_em  TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  PRIMARY KEY (grupo_id, usuario_id),
  CONSTRAINT fk_grupo_membro_grupo FOREIGN KEY (grupo_id)
    REFERENCES grupo (id) ON DELETE CASCADE,
  CONSTRAINT fk_grupo_membro_usuario FOREIGN KEY (usuario_id)
    REFERENCES usuario (id) ON DELETE CASCADE,
  CONSTRAINT ck_grupo_membro_papel CHECK (papel IN ('CRIADOR', 'MEMBRO'))
);

CREATE INDEX ix_grupo_membro_usuario ON grupo_membro (usuario_id);

-- ------------------------------------------------------------
-- Conversas e mensagens
-- ------------------------------------------------------------
CREATE TABLE conversa (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo           VARCHAR2(7) NOT NULL,
  evento_id      NUMBER,
  grupo_id       NUMBER,
  usuario_a_id   NUMBER,
  usuario_b_id   NUMBER,
  criado_em      TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT fk_conversa_evento FOREIGN KEY (evento_id)
    REFERENCES evento (id) ON DELETE CASCADE,
  CONSTRAINT fk_conversa_grupo FOREIGN KEY (grupo_id)
    REFERENCES grupo (id) ON DELETE CASCADE,
  CONSTRAINT fk_conversa_usuario_a FOREIGN KEY (usuario_a_id)
    REFERENCES usuario (id) ON DELETE CASCADE,
  CONSTRAINT fk_conversa_usuario_b FOREIGN KEY (usuario_b_id)
    REFERENCES usuario (id) ON DELETE CASCADE,
  CONSTRAINT ck_conversa_tipo CHECK (
    (tipo = 'EVENTO' AND evento_id IS NOT NULL AND grupo_id IS NULL
      AND usuario_a_id IS NULL AND usuario_b_id IS NULL)
    OR
    (tipo = 'DIRETA' AND evento_id IS NULL AND grupo_id IS NULL
      AND usuario_a_id IS NOT NULL AND usuario_b_id IS NOT NULL
      AND usuario_a_id < usuario_b_id)
    OR
    (tipo = 'GRUPO' AND evento_id IS NULL AND grupo_id IS NOT NULL
      AND usuario_a_id IS NULL AND usuario_b_id IS NULL)
  )
);

CREATE UNIQUE INDEX uq_conversa_evento ON conversa (evento_id);
CREATE UNIQUE INDEX uq_conversa_grupo ON conversa (grupo_id);
CREATE UNIQUE INDEX uq_conversa_direta ON conversa (usuario_a_id, usuario_b_id);
CREATE INDEX ix_conversa_usuario_a ON conversa (usuario_a_id);
CREATE INDEX ix_conversa_usuario_b ON conversa (usuario_b_id);

CREATE TABLE mensagem (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversa_id  NUMBER NOT NULL,
  autor_id     NUMBER NOT NULL,
  texto        VARCHAR2(2000) NOT NULL,
  criado_em    TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT fk_mensagem_conversa FOREIGN KEY (conversa_id)
    REFERENCES conversa (id) ON DELETE CASCADE,
  CONSTRAINT fk_mensagem_autor FOREIGN KEY (autor_id)
    REFERENCES usuario (id) ON DELETE CASCADE,
  CONSTRAINT ck_mensagem_texto CHECK (LENGTH(TRIM(texto)) > 0)
);

CREATE INDEX ix_mensagem_conversa_id ON mensagem (conversa_id, id);

-- ------------------------------------------------------------
-- Leitura de conversas (contador de não lidas)
-- ------------------------------------------------------------
CREATE TABLE conversa_leitura (
  conversa_id        NUMBER NOT NULL,
  usuario_id         NUMBER NOT NULL,
  ultima_mensagem_id NUMBER DEFAULT 0 NOT NULL,
  atualizado_em      TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  PRIMARY KEY (conversa_id, usuario_id),
  CONSTRAINT fk_leitura_conversa FOREIGN KEY (conversa_id)
    REFERENCES conversa (id) ON DELETE CASCADE,
  CONSTRAINT fk_leitura_usuario FOREIGN KEY (usuario_id)
    REFERENCES usuario (id) ON DELETE CASCADE,
  CONSTRAINT ck_leitura_mensagem CHECK (ultima_mensagem_id >= 0)
);

CREATE INDEX ix_leitura_usuario ON conversa_leitura (usuario_id);

-- ------------------------------------------------------------
-- Conversas ocultas por usuário ("apagar para mim")
-- ------------------------------------------------------------
CREATE TABLE conversa_oculta (
  conversa_id              NUMBER NOT NULL,
  usuario_id               NUMBER NOT NULL,
  ocultada_ate_mensagem_id NUMBER DEFAULT 0 NOT NULL,
  criado_em                TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  PRIMARY KEY (conversa_id, usuario_id),
  CONSTRAINT fk_oculta_conversa FOREIGN KEY (conversa_id)
    REFERENCES conversa (id) ON DELETE CASCADE,
  CONSTRAINT fk_oculta_usuario FOREIGN KEY (usuario_id)
    REFERENCES usuario (id) ON DELETE CASCADE,
  CONSTRAINT ck_oculta_mensagem CHECK (ocultada_ate_mensagem_id >= 0)
);

CREATE INDEX ix_oculta_usuario ON conversa_oculta (usuario_id);

