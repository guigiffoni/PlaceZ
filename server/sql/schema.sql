  CONSTRAINT uq_opcao_enquete_data UNIQUE (enquete_id, data_opcao),
  CONSTRAINT fk_opcao_enquete FOREIGN KEY (enquete_id)
    REFERENCES enquete_disponibilidade (id) ON DELETE CASCADE
);

