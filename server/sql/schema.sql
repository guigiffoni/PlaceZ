-- ------------------------------------------------------------
-- Usuários e sessões
-- ------------------------------------------------------------
CREATE TABLE usuario (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome         VARCHAR2(120) NOT NULL,
  username     VARCHAR2(40)  NOT NULL,
  senha_hash   VARCHAR2(255) NOT NULL,
  fcm_token    VARCHAR2(512),
  criado_em    TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT uq_usuario_username UNIQUE (username),
  CONSTRAINT ck_usuario_username CHECK (REGEXP_LIKE(username, '^[a-z0-9._-]{3,40}$'))
);

CREATE TABLE sessao (
  token_hash   CHAR(64) PRIMARY KEY,
  usuario_id   NUMBER NOT NULL,
  criado_em    TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  expira_em    TIMESTAMP NOT NULL,
  CONSTRAINT fk_sessao_usuario FOREIGN KEY (usuario_id)
    REFERENCES usuario (id) ON DELETE CASCADE
);

CREATE INDEX ix_sessao_usuario ON sessao (usuario_id);
CREATE INDEX ix_sessao_expira ON sessao (expira_em);

-- ------------------------------------------------------------
-- Amizades e bloqueios
-- ------------------------------------------------------------
CREATE TABLE amizade (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitante_id  NUMBER NOT NULL,
  destinatario_id NUMBER NOT NULL,
  status          CHAR(1) DEFAULT 'P' NOT NULL,
  criado_em       TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  respondido_em   TIMESTAMP,
  CONSTRAINT fk_amizade_solicitante FOREIGN KEY (solicitante_id)
    REFERENCES usuario (id) ON DELETE CASCADE,
  CONSTRAINT fk_amizade_destinatario FOREIGN KEY (destinatario_id)
    REFERENCES usuario (id) ON DELETE CASCADE,
  CONSTRAINT ck_amizade_status CHECK (status IN ('P', 'A', 'R')),
  CONSTRAINT ck_amizade_par CHECK (solicitante_id <> destinatario_id)
);

CREATE UNIQUE INDEX uq_amizade_par
  ON amizade (LEAST(solicitante_id, destinatario_id), GREATEST(solicitante_id, destinatario_id));
CREATE INDEX ix_amizade_destinatario_status ON amizade (destinatario_id, status);
CREATE INDEX ix_amizade_solicitante ON amizade (solicitante_id);

CREATE TABLE bloqueio (
  bloqueador_id NUMBER NOT NULL,
  bloqueado_id  NUMBER NOT NULL,
  criado_em     TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  PRIMARY KEY (bloqueador_id, bloqueado_id),
  CONSTRAINT fk_bloqueio_bloqueador FOREIGN KEY (bloqueador_id)
    REFERENCES usuario (id) ON DELETE CASCADE,
  CONSTRAINT fk_bloqueio_bloqueado FOREIGN KEY (bloqueado_id)
    REFERENCES usuario (id) ON DELETE CASCADE,
  CONSTRAINT ck_bloqueio_par CHECK (bloqueador_id <> bloqueado_id)
);

CREATE INDEX ix_bloqueio_bloqueado ON bloqueio (bloqueado_id);

-- ------------------------------------------------------------
-- Locais e eventos
-- ------------------------------------------------------------
CREATE TABLE local (
  id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome              VARCHAR2(160) NOT NULL,
  endereco          VARCHAR2(300),
  categoria         VARCHAR2(60),
  distancia_metros  NUMBER(10, 2),
  latitude          NUMBER(9, 6),
  longitude         NUMBER(9, 6),
  criado_em         TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL
);

CREATE TABLE evento (
  id                         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo                     VARCHAR2(160) NOT NULL,
  descricao                  VARCHAR2(2000),
  inicio_em                  TIMESTAMP,
  fim_em                     TIMESTAMP,
  local_id                   NUMBER,
  criador_id                 NUMBER NOT NULL,
  privado                    CHAR(1) DEFAULT 'S' NOT NULL,
  permitir_membros_convidar  CHAR(1) DEFAULT 'N' NOT NULL,
  status                     VARCHAR2(10) DEFAULT 'CONFIRMADO' NOT NULL,
  criado_em                  TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  atualizado_em              TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT fk_evento_local FOREIGN KEY (local_id)
    REFERENCES local (id),
  CONSTRAINT fk_evento_criador FOREIGN KEY (criador_id)
    REFERENCES usuario (id),
  CONSTRAINT ck_evento_privado CHECK (privado IN ('S', 'N')),
  CONSTRAINT ck_evento_permitir CHECK (permitir_membros_convidar IN ('S', 'N')),
  CONSTRAINT ck_evento_status CHECK (status IN ('RASCUNHO', 'CONFIRMADO', 'CANCELADO')),
  CONSTRAINT ck_evento_datas CHECK (fim_em IS NULL OR inicio_em IS NULL OR fim_em >= inicio_em)
);

CREATE INDEX ix_evento_criador_inicio ON evento (criador_id, inicio_em);
CREATE INDEX ix_evento_status ON evento (status);
CREATE INDEX ix_evento_local ON evento (local_id);

CREATE TABLE convidado_evento (
  evento_id      NUMBER NOT NULL,
  usuario_id     NUMBER NOT NULL,
  convidado_por  NUMBER,
  papel          VARCHAR2(10) DEFAULT 'CONVIDADO' NOT NULL,
  rsvp           VARCHAR2(6),
  criado_em      TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  respondido_em  TIMESTAMP,
  PRIMARY KEY (evento_id, usuario_id),
  CONSTRAINT fk_convidado_evento FOREIGN KEY (evento_id)
    REFERENCES evento (id) ON DELETE CASCADE,
  CONSTRAINT fk_convidado_usuario FOREIGN KEY (usuario_id)
    REFERENCES usuario (id) ON DELETE CASCADE,
  CONSTRAINT fk_convidado_por FOREIGN KEY (convidado_por)
    REFERENCES usuario (id),
  CONSTRAINT ck_convidado_papel CHECK (papel IN ('CRIADOR', 'CONVIDADO')),
  CONSTRAINT ck_convidado_rsvp CHECK (rsvp IS NULL OR rsvp IN ('VOU', 'TALVEZ')),
  CONSTRAINT ck_convidado_criador CHECK (
    papel <> 'CRIADOR' OR (rsvp IS NOT NULL AND rsvp = 'VOU')
  )
);

CREATE INDEX ix_convidado_usuario_evento ON convidado_evento (usuario_id, evento_id);
CREATE INDEX ix_convidado_evento_rsvp ON convidado_evento (evento_id, rsvp);
CREATE INDEX ix_convidado_convidado_por ON convidado_evento (convidado_por, criado_em);

-- ------------------------------------------------------------
-- Combinação de dias
-- ------------------------------------------------------------
CREATE TABLE enquete_disponibilidade (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evento_id     NUMBER NOT NULL,
  data_inicio   DATE NOT NULL,
  data_fim      DATE NOT NULL,
  dias_semana   VARCHAR2(20) NOT NULL,
  hora_inicio   VARCHAR2(5) NOT NULL,
  hora_fim      VARCHAR2(5) NOT NULL,
  fuso_offset_minutos NUMBER(4) DEFAULT 0 NOT NULL,
  criado_em     TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT uq_enquete_evento UNIQUE (evento_id),
  CONSTRAINT fk_enquete_evento FOREIGN KEY (evento_id)
    REFERENCES evento (id) ON DELETE CASCADE,
  CONSTRAINT ck_enquete_intervalo CHECK (data_fim >= data_inicio)
);

CREATE TABLE opcao_disponibilidade (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enquete_id   NUMBER NOT NULL,
  data_opcao   DATE NOT NULL,
  hora_inicio  VARCHAR2(5) NOT NULL,
  hora_fim     VARCHAR2(5) NOT NULL,
  CONSTRAINT uq_opcao_enquete_data UNIQUE (enquete_id, data_opcao),
  CONSTRAINT fk_opcao_enquete FOREIGN KEY (enquete_id)
    REFERENCES enquete_disponibilidade (id) ON DELETE CASCADE
);

-- CREATE INDEX ix_opcao_enquete_data ON opcao_disponibilidade (enquete_id, data_opcao);

CREATE TABLE voto_disponibilidade (
  opcao_id       NUMBER NOT NULL,
  usuario_id     NUMBER NOT NULL,
  status         VARCHAR2(12) NOT NULL,
  atualizado_em  TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  PRIMARY KEY (opcao_id, usuario_id),
  CONSTRAINT fk_voto_opcao FOREIGN KEY (opcao_id)
    REFERENCES opcao_disponibilidade (id) ON DELETE CASCADE,
  CONSTRAINT fk_voto_usuario FOREIGN KEY (usuario_id)
    REFERENCES usuario (id) ON DELETE CASCADE,
  CONSTRAINT ck_voto_status CHECK (status IN ('DISPONIVEL', 'INDISPONIVEL'))
);

CREATE INDEX ix_voto_opcao_status ON voto_disponibilidade (opcao_id, status);

-- ------------------------------------------------------------
-- Conversas e mensagens
-- ------------------------------------------------------------
CREATE TABLE conversa (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo           VARCHAR2(7) NOT NULL,
  evento_id      NUMBER,
  usuario_a_id   NUMBER,
  usuario_b_id   NUMBER,
  criado_em      TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT fk_conversa_evento FOREIGN KEY (evento_id)
    REFERENCES evento (id) ON DELETE CASCADE,
  CONSTRAINT fk_conversa_usuario_a FOREIGN KEY (usuario_a_id)
    REFERENCES usuario (id) ON DELETE CASCADE,
  CONSTRAINT fk_conversa_usuario_b FOREIGN KEY (usuario_b_id)
    REFERENCES usuario (id) ON DELETE CASCADE,
  CONSTRAINT ck_conversa_tipo CHECK (
    (tipo = 'EVENTO' AND evento_id IS NOT NULL AND usuario_a_id IS NULL AND usuario_b_id IS NULL)
    OR
    (tipo = 'DIRETA' AND evento_id IS NULL AND usuario_a_id IS NOT NULL
      AND usuario_b_id IS NOT NULL AND usuario_a_id < usuario_b_id)
  )
);

CREATE UNIQUE INDEX uq_conversa_evento ON conversa (evento_id);
CREATE UNIQUE INDEX uq_conversa_direta ON conversa (usuario_a_id, usuario_b_id);
CREATE INDEX ix_conversa_usuario_a ON conversa (usuario_a_id);
CREATE INDEX ix_conversa_usuario_b ON conversa (usuario_b_id);

CREATE TABLE mensagem (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversa_id  NUMBER NOT NULL,
  autor_id     NUMBER NOT NULL,
  texto        VARCHAR2(2000) NOT NULL,
  criado_em    TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT fk_mensagem_conversa FOREIGN KEY (conversa_id)
    REFERENCES conversa (id) ON DELETE CASCADE,
  CONSTRAINT fk_mensagem_autor FOREIGN KEY (autor_id)
    REFERENCES usuario (id) ON DELETE CASCADE,
  CONSTRAINT ck_mensagem_texto CHECK (LENGTH(TRIM(texto)) > 0)
);

CREATE INDEX ix_mensagem_conversa_id ON mensagem (conversa_id, id);

