-- P2 — detalhes do catálogo: descrição, faixa de preço, itens e avaliações.
-- Idempotente.

DECLARE
  v_existe NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_existe FROM user_tab_columns
   WHERE table_name = 'CATALOGO_LUGAR' AND column_name = 'DESCRICAO';
  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE catalogo_lugar ADD (descricao VARCHAR2(2000))';
  END IF;

  SELECT COUNT(*) INTO v_existe FROM user_tab_columns
   WHERE table_name = 'CATALOGO_LUGAR' AND column_name = 'FAIXA_PRECO';
  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE catalogo_lugar ADD (faixa_preco VARCHAR2(60))';
  END IF;

  SELECT COUNT(*) INTO v_existe FROM user_tab_columns
   WHERE table_name = 'CATALOGO_LUGAR' AND column_name = 'AVALIACAO_MEDIA';
  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE q'[
      ALTER TABLE catalogo_lugar ADD (
        avaliacao_media NUMBER(3, 2) DEFAULT 0 NOT NULL
      )
    ]';
  END IF;

  SELECT COUNT(*) INTO v_existe FROM user_tab_columns
   WHERE table_name = 'CATALOGO_LUGAR' AND column_name = 'AVALIACAO_TOTAL';
  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE q'[
      ALTER TABLE catalogo_lugar ADD (
        avaliacao_total NUMBER DEFAULT 0 NOT NULL
      )
    ]';
  END IF;

  SELECT COUNT(*) INTO v_existe FROM user_constraints
   WHERE constraint_name = 'CK_CATALOGO_AVALIACAO';
  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE q'[
      ALTER TABLE catalogo_lugar ADD CONSTRAINT ck_catalogo_avaliacao
        CHECK (avaliacao_media BETWEEN 0 AND 5 AND avaliacao_total >= 0)
    ]';
  END IF;

  SELECT COUNT(*) INTO v_existe FROM user_tables
   WHERE table_name = 'CATALOGO_LUGAR_ITEM';
  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE catalogo_lugar_item (
        id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        lugar_id NUMBER NOT NULL,
        nome     VARCHAR2(120) NOT NULL,
        ordem    NUMBER DEFAULT 0 NOT NULL,
        CONSTRAINT fk_item_lugar FOREIGN KEY (lugar_id)
          REFERENCES catalogo_lugar (id) ON DELETE CASCADE
      )
    ]';
    EXECUTE IMMEDIATE
      'CREATE INDEX ix_item_lugar ON catalogo_lugar_item (lugar_id, ordem)';
  END IF;

  SELECT COUNT(*) INTO v_existe FROM user_tables
   WHERE table_name = 'CATALOGO_LUGAR_AVALIACAO';
  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE catalogo_lugar_avaliacao (
        id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        lugar_id      NUMBER NOT NULL,
        usuario_id    NUMBER,
        autor_nome    VARCHAR2(120),
        nota          NUMBER(1) NOT NULL,
        comentario    VARCHAR2(1000),
        criado_em     TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
        atualizado_em TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
        CONSTRAINT fk_avaliacao_lugar FOREIGN KEY (lugar_id)
          REFERENCES catalogo_lugar (id) ON DELETE CASCADE,
        CONSTRAINT fk_avaliacao_usuario FOREIGN KEY (usuario_id)
          REFERENCES usuario (id) ON DELETE CASCADE,
        CONSTRAINT ck_avaliacao_nota CHECK (nota BETWEEN 1 AND 5)
      )
    ]';
    EXECUTE IMMEDIATE q'[
      CREATE INDEX ix_avaliacao_lugar
        ON catalogo_lugar_avaliacao (lugar_id, criado_em)
    ]';
    EXECUTE IMMEDIATE q'[
      CREATE INDEX ix_avaliacao_usuario
        ON catalogo_lugar_avaliacao (usuario_id)
    ]';
    EXECUTE IMMEDIATE q'[
      CREATE UNIQUE INDEX uq_avaliacao_usuario_lugar
        ON catalogo_lugar_avaliacao (
          lugar_id,
          CASE WHEN usuario_id IS NOT NULL THEN usuario_id END
        )
    ]';
  END IF;
END;
/
