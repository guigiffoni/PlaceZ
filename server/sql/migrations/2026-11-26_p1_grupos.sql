-- P1 — chat em grupo entre amigos.
-- Idempotente: cria as tabelas, a coluna grupo_id em conversa e atualiza a
-- constraint de tipo para aceitar GRUPO.

DECLARE
  v_existe NUMBER;
BEGIN
  SELECT COUNT(*)
    INTO v_existe
    FROM user_tables
   WHERE table_name = 'GRUPO';

  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE grupo (
        id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome        VARCHAR2(120) NOT NULL,
        criador_id  NUMBER NOT NULL,
        criado_em   TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
        CONSTRAINT fk_grupo_criador FOREIGN KEY (criador_id)
          REFERENCES usuario (id)
      )
    ]';
  END IF;

  SELECT COUNT(*)
    INTO v_existe
    FROM user_tables
   WHERE table_name = 'GRUPO_MEMBRO';

  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE grupo_membro (
        grupo_id   NUMBER NOT NULL,
        usuario_id NUMBER NOT NULL,
        papel      VARCHAR2(10) DEFAULT 'MEMBRO' NOT NULL,
        criado_em  TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
        PRIMARY KEY (grupo_id, usuario_id),
        CONSTRAINT fk_grupo_membro_grupo FOREIGN KEY (grupo_id)
          REFERENCES grupo (id) ON DELETE CASCADE,
        CONSTRAINT fk_grupo_membro_usuario FOREIGN KEY (usuario_id)
          REFERENCES usuario (id) ON DELETE CASCADE,
        CONSTRAINT ck_grupo_membro_papel CHECK (papel IN ('CRIADOR', 'MEMBRO'))
      )
    ]';
  END IF;

  SELECT COUNT(*)
    INTO v_existe
    FROM user_indexes
   WHERE index_name = 'IX_GRUPO_MEMBRO_USUARIO';

  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE
      'CREATE INDEX ix_grupo_membro_usuario ON grupo_membro (usuario_id)';
  END IF;

  SELECT COUNT(*)
    INTO v_existe
    FROM user_tab_columns
   WHERE table_name = 'CONVERSA'
     AND column_name = 'GRUPO_ID';

  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE conversa ADD (grupo_id NUMBER)';
  END IF;

  SELECT COUNT(*)
    INTO v_existe
    FROM user_constraints
   WHERE table_name = 'CONVERSA'
     AND constraint_name = 'CK_CONVERSA_TIPO';

  IF v_existe > 0 THEN
    EXECUTE IMMEDIATE
      'ALTER TABLE conversa DROP CONSTRAINT ck_conversa_tipo';
  END IF;

  EXECUTE IMMEDIATE q'[
    ALTER TABLE conversa ADD CONSTRAINT ck_conversa_tipo CHECK (
      (tipo = 'EVENTO' AND evento_id IS NOT NULL AND grupo_id IS NULL
        AND usuario_a_id IS NULL AND usuario_b_id IS NULL)
      OR
      (tipo = 'DIRETA' AND evento_id IS NULL AND grupo_id IS NULL
        AND usuario_a_id IS NOT NULL AND usuario_b_id IS NOT NULL
        AND usuario_a_id < usuario_b_id)
      OR
      (tipo = 'GRUPO' AND evento_id IS NULL AND grupo_id IS NOT NULL
        AND usuario_a_id IS NULL AND usuario_b_id IS NULL)
    )
  ]';

  SELECT COUNT(*)
    INTO v_existe
    FROM user_constraints
   WHERE table_name = 'CONVERSA'
     AND constraint_name = 'FK_CONVERSA_GRUPO';

  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE q'[
      ALTER TABLE conversa ADD CONSTRAINT fk_conversa_grupo
      FOREIGN KEY (grupo_id) REFERENCES grupo (id) ON DELETE CASCADE
    ]';
  END IF;

  SELECT COUNT(*)
    INTO v_existe
    FROM user_indexes
   WHERE index_name = 'UQ_CONVERSA_GRUPO';

  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE
      'CREATE UNIQUE INDEX uq_conversa_grupo ON conversa (grupo_id)';
  END IF;
END;
