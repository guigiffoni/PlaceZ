-- P1 — localização aproximada, catálogo real e sugestões de locais.
-- Idempotente: cria as tabelas, a coluna em usuario e a FK.

DECLARE
  v_existe NUMBER;
BEGIN
  SELECT COUNT(*)
    INTO v_existe
    FROM user_tables
   WHERE table_name = 'REGIAO_APROXIMADA';

  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE regiao_aproximada (
        id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome       VARCHAR2(80) NOT NULL,
        cidade     VARCHAR2(80) NOT NULL,
        latitude   NUMBER(9, 6) NOT NULL,
        longitude  NUMBER(9, 6) NOT NULL,
        CONSTRAINT uq_regiao_aproximada UNIQUE (nome, cidade)
      )
    ]';
  END IF;

  SELECT COUNT(*)
    INTO v_existe
    FROM user_tables
   WHERE table_name = 'CATALOGO_LUGAR';

  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE catalogo_lugar (
        id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome       VARCHAR2(160) NOT NULL,
        endereco   VARCHAR2(300),
        categoria  VARCHAR2(60),
        cidade     VARCHAR2(80) NOT NULL,
        latitude   NUMBER(9, 6) NOT NULL,
        longitude  NUMBER(9, 6) NOT NULL,
        CONSTRAINT uq_catalogo_lugar UNIQUE (nome, cidade)
      )
    ]';
  END IF;

  SELECT COUNT(*)
    INTO v_existe
    FROM user_indexes
   WHERE index_name = 'IX_CATALOGO_LUGAR_NOME';

  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE
      'CREATE INDEX ix_catalogo_lugar_nome ON catalogo_lugar (nome)';
  END IF;

  SELECT COUNT(*)
    INTO v_existe
    FROM user_indexes
   WHERE index_name = 'IX_CATALOGO_LUGAR_CIDADE';

  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE
      'CREATE INDEX ix_catalogo_lugar_cidade ON catalogo_lugar (cidade)';
  END IF;

  SELECT COUNT(*)
    INTO v_existe
    FROM user_tab_columns
   WHERE table_name = 'USUARIO' AND column_name = 'REGIAO_ID';

  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE usuario ADD (regiao_id NUMBER)';
  END IF;

  SELECT COUNT(*)
    INTO v_existe
    FROM user_constraints
   WHERE table_name = 'USUARIO'
     AND constraint_name = 'FK_USUARIO_REGIAO';

  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE q'[
      ALTER TABLE usuario ADD CONSTRAINT fk_usuario_regiao
      FOREIGN KEY (regiao_id) REFERENCES regiao_aproximada (id)
      ON DELETE SET NULL
    ]';
  END IF;
END;
